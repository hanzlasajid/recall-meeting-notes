"""Render the Markdown report as a self-contained HTML page (images inlined, Mermaid diagrams drawn)."""
import base64
import html
import re
from pathlib import Path

import markdown

CSS = """
:root{--ink:#1f2328;--quiet:#59636e;--line:#d1d9e0;--tint:#f6f8fa;--accent:#0969da}
@media (prefers-color-scheme:dark){:root{--ink:#e6edf3;--quiet:#9198a1;--line:#3d444d;--tint:#151b23;--accent:#4493f8}
 body{background:#0d1117}}
body{font:16px/1.6 -apple-system,BlinkMacSystemFont,"Segoe UI",Helvetica,Arial,sans-serif;color:var(--ink);
 max-width:880px;margin:40px auto;padding:0 24px}
h1{font-size:2em;line-height:1.25;margin-bottom:4px} h1+p{color:var(--quiet);margin-top:0}
h2{border-bottom:1px solid var(--line);padding-bottom:6px;margin-top:40px} h3{margin-top:28px}
table{border-collapse:collapse;width:100%;margin:16px 0;font-size:14px}
th,td{border:1px solid var(--line);padding:6px 10px;text-align:left;vertical-align:top} th{background:var(--tint)}
code{background:var(--tint);padding:1px 5px;border-radius:4px;font-size:90%}
pre{background:var(--tint);padding:12px;border-radius:6px;overflow:auto}
img{max-width:100%;border:1px solid var(--line);border-radius:6px;display:block;margin:12px 0 4px}
img+em,p>em:only-child{color:var(--quiet);font-size:14px}
li{margin:3px 0} ul.tasks{list-style:none;padding-left:4px}
.mermaid{background:var(--tint);border-radius:6px;padding:12px;text-align:center}
footer{margin:48px 0 24px;color:var(--quiet);font-size:13px}
"""


def _inline_images(body: str, base: Path) -> str:
    def repl(m):
        src = m.group(2)
        p = base / src
        if p.exists() and p.suffix.lower() in (".jpg", ".jpeg", ".png"):
            mime = "image/png" if p.suffix.lower() == ".png" else "image/jpeg"
            src = f"data:{mime};base64," + base64.b64encode(p.read_bytes()).decode()
        return f'{m.group(1)}src="{src}"'
    return re.sub(r'(<img[^>]*?)src="([^"]+)"', repl, body)


def _tasks(body: str) -> str:
    body = re.sub(r"<li>\s*\[ \]\s*", '<li><input type="checkbox" disabled> ', body)
    return re.sub(r"<li>\s*\[[xX]\]\s*", '<li><input type="checkbox" checked disabled> ', body)


def _captions(body: str) -> str:
    # show each image's alt text as a caption under it
    return re.sub(r'(<img alt="([^"]*)"[^>]*>)', lambda m: f"{m.group(1)}<em>{m.group(2)}</em>", body)


def _mermaid(body: str) -> str:
    return re.sub(r'<pre><code class="language-mermaid">(.*?)</code></pre>',
                  lambda m: f'<div class="mermaid">{m.group(1)}</div>', body, flags=re.S)


def to_html(md_text: str, base: Path, embed_images=True) -> str:
    body = markdown.markdown(md_text, extensions=["tables", "fenced_code", "sane_lists"])
    body = _mermaid(_tasks(body))
    if embed_images:
        body = _inline_images(body, base)
    body = _captions(body)
    m = re.search(r"<h1>(.*?)</h1>", body)
    title = html.unescape(re.sub("<[^>]+>", "", m.group(1))) if m else "Meeting report"
    return f"""<!DOCTYPE html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>{html.escape(title)}</title><style>{CSS}</style></head>
<body>{body}
<footer>Generated by Recall. Transcript and screenshots are in the same folder.</footer>
<script type="module">
import mermaid from "https://cdn.jsdelivr.net/npm/mermaid@11/dist/mermaid.esm.min.mjs";
mermaid.initialize({{startOnLoad:true, theme: matchMedia("(prefers-color-scheme: dark)").matches ? "dark" : "default"}});
</script></body></html>"""
